#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_ja3_client_values() {
        let map = ja3_client_values();
        assert!(map.contains_key("18e9afaf91db6f8a2470e7435c2a1d6b"));
        assert_eq!(map.get("18e9afaf91db6f8a2470e7435c2a1d6b"), Some(&("Masscan", None)));
    }

    #[test]
    fn test_user_agent_values() {
        let map = user_agent_values();
        assert!(map.contains_key("masscan/1.0 (https://github.com/robertdavidgraham/masscan)"));
    }

    #[test]
    fn test_udp_probes() {
        let map = udp_probes();
        assert!(!map.is_empty());
    }
}
